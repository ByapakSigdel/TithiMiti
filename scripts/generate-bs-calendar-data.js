#!/usr/bin/env node
/**
 * Regenerates src/domain/calendar/bsCalendarData.ts from the primary calendar
 * API (cal.mahansigdel.com.np). The app uses that table to render month grids
 * and convert AD<->BS dates instantly and offline; the network is only needed
 * for tithi/panchang/event details.
 *
 * Run whenever the API gains new years:  node scripts/generate-bs-calendar-data.js
 *
 * The script verifies that every month is contiguous (days 1..N present) and
 * that each month's first AD date equals the previous month's first AD date
 * plus its length, so a bad upstream month can never corrupt the table.
 */

const fs = require('fs');
const path = require('path');

const BASE = 'https://cal.mahansigdel.com.np';
// Probed range of the API as of 2026: BS 2080/01 .. 2085/12.
const START_YEAR = 2080;
const END_YEAR = 2085;

function tryParse(text) {
  try {
    return JSON.parse(text);
  } catch {
    // Some months ship bare dates (e.g. `: 2023-04-14`) — quote them first.
    const sanitized = text.replace(
      /(:\s*)(\d{4}-\d{2}-\d{2}(?:T[^\s",}]*)?)/g,
      '$1"$2"',
    );
    return JSON.parse(sanitized);
  }
}

function toIso(raw) {
  const m = String(raw).match(/(\d{4})-(\d{1,2})-(\d{1,2})/);
  if (!m) return null;
  return `${m[1]}-${m[2].padStart(2, '0')}-${m[3].padStart(2, '0')}`;
}

function isoToUtcDays(iso) {
  const [y, m, d] = iso.split('-').map(Number);
  return Date.UTC(y, m - 1, d) / 86400000;
}

async function fetchMonth(year, month) {
  const url = `${BASE}/${year}/${String(month).padStart(2, '0')}.json`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url} -> HTTP ${res.status}`);
  const raw = tryParse(await res.text());
  if (!Array.isArray(raw) || raw.length === 0) throw new Error(`${url} -> empty`);

  const days = raw.map((item) => ({
    bsDay: parseInt(item.calendarInfo?.dates?.bs?.day?.en ?? '0', 10),
    adISO: toIso(item.calendarInfo?.dates?.ad?.full?.en ?? ''),
  }));

  days.sort((a, b) => a.bsDay - b.bsDay);
  days.forEach((d, i) => {
    if (d.bsDay !== i + 1 || !d.adISO) {
      throw new Error(`${url} -> non-contiguous or unparsable day at index ${i}`);
    }
  });
  return { length: days.length, firstAdISO: days[0].adISO };
}

async function main() {
  const monthDays = []; // monthDays[yearIndex][monthIndex]
  let epochAdISO = null;
  let expectedNextFirstDays = null;

  for (let year = START_YEAR; year <= END_YEAR; year++) {
    const row = [];
    for (let month = 1; month <= 12; month++) {
      const { length, firstAdISO } = await fetchMonth(year, month);
      const firstDays = isoToUtcDays(firstAdISO);

      if (epochAdISO === null) epochAdISO = firstAdISO;
      if (expectedNextFirstDays !== null && firstDays !== expectedNextFirstDays) {
        throw new Error(
          `Discontinuity at BS ${year}/${month}: first AD day ${firstAdISO} ` +
          `does not follow the previous month`,
        );
      }
      expectedNextFirstDays = firstDays + length;
      row.push(length);
      process.stdout.write(`BS ${year}/${String(month).padStart(2, '0')}: ${length} days (from ${firstAdISO})\n`);
    }
    monthDays.push(row);
  }

  const totalDays = monthDays.flat().reduce((a, b) => a + b, 0);
  const out = `// AUTO-GENERATED by scripts/generate-bs-calendar-data.js — do not edit by hand.
// Source: ${BASE} (BS ${START_YEAR}/01 .. ${END_YEAR}/12), verified contiguous.

/** First BS year covered by BS_MONTH_DAYS. */
export const BS_DATA_START_YEAR = ${START_YEAR};

/** Last BS year covered by BS_MONTH_DAYS. */
export const BS_DATA_END_YEAR = ${END_YEAR};

/** AD date (YYYY-MM-DD) of Baisakh 1, ${START_YEAR} BS. */
export const BS_EPOCH_AD_ISO = '${epochAdISO}';

/** Days in each BS month, one row of 12 per year from BS_DATA_START_YEAR. */
export const BS_MONTH_DAYS: number[][] = [
${monthDays.map((row, i) => `  /* ${START_YEAR + i} */ [${row.join(', ')}],`).join('\n')}
];

/** Total days covered (${totalDays}): AD ${epochAdISO} onward. */
export const BS_DATA_TOTAL_DAYS = ${totalDays};
`;

  const dest = path.join(__dirname, '..', 'src', 'domain', 'calendar', 'bsCalendarData.ts');
  fs.writeFileSync(dest, out);
  process.stdout.write(`\nWrote ${dest} (${totalDays} days, epoch ${epochAdISO})\n`);
}

main().catch((e) => {
  process.stderr.write(`FAILED: ${e.message}\n`);
  process.exit(1);
});
